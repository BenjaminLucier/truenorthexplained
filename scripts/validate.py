"""Validate True North Explained content.

Checks internal links, quiz question IDs/pages/answers, and page status.
Run from the project root:

    uv run --with pyyaml python scripts/validate.py
"""

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"

errors: list[str] = []
warnings: list[str] = []


def front_matter(path: Path) -> dict:
    text = path.read_text()
    if not text.startswith("---\n"):
        errors.append(f"{path.relative_to(ROOT)}: missing front matter")
        return {}
    end = text.index("\n---", 4)
    return yaml.safe_load(text[4:end]) or {}


# --- Build map of site path -> file ---------------------------------------
pages: dict[str, Path] = {}
for f in CONTENT.rglob("*.en.md"):
    rel = f.relative_to(CONTENT)
    parts = list(rel.parts)
    name = parts[-1].removesuffix(".en.md")
    if parts[0] == "learn":
        module = re.sub(r"^\d+-", "", parts[1])
        site = f"learn/{module}" if name == "index" else f"learn/{module}/{name}"
    elif parts[0] == "provinces":
        site = "provinces" if name == "index" else f"provinces/{name}"
    else:
        site = "" if name == "home" else name
    pages[site] = f

GENERATED = {"tour", "quizzes"}
valid_paths = set(pages) | GENERATED

# --- Pages: status, links ------------------------------------------------
link_re = re.compile(r"\]\((/[^)\s#]*)(?:#[^)]*)?\)")
status_counts: dict[str, int] = {}
for site, f in sorted(pages.items()):
    fm = front_matter(f)
    status = fm.get("status", "missing")
    status_counts[status] = status_counts.get(status, 0) + 1
    if status == "stub":
        warnings.append(f"{f.relative_to(ROOT)}: still a stub")
    for m in link_re.finditer(f.read_text()):
        target = m.group(1).strip("/")
        if target not in valid_paths:
            errors.append(f"{f.relative_to(ROOT)}: broken internal link /{target}")

# --- Quizzes -------------------------------------------------------------
seen_ids: dict[str, str] = {}
per_page: dict[str, int] = {}
for qf in sorted((CONTENT / "quizzes").glob("*.en.yaml")):
    rel = qf.relative_to(ROOT)
    try:
        questions = yaml.safe_load(qf.read_text()) or []
    except yaml.YAMLError as e:
        errors.append(f"{rel}: YAML error: {e}")
        continue
    for q in questions:
        qid = q.get("id", "<no id>")
        where = f"{rel}: {qid}"
        if qid in seen_ids:
            errors.append(f"{where}: duplicate id (also in {seen_ids[qid]})")
        seen_ids[qid] = str(rel)
        for key in ("pages", "type", "question", "answer", "explanation", "source"):
            if key not in q:
                errors.append(f"{where}: missing '{key}'")
        for p in q.get("pages", []):
            if p not in pages:
                errors.append(f"{where}: unknown page '{p}'")
            per_page[p] = per_page.get(p, 0) + 1
        t, ans, opts = q.get("type"), q.get("answer"), q.get("options")
        if t == "true-false":
            if not isinstance(ans, bool):
                errors.append(f"{where}: true-false answer must be true/false")
        elif t == "single":
            if not opts or not isinstance(ans, int) or not 0 <= ans < len(opts):
                errors.append(f"{where}: single answer index out of range")
        elif t == "multi":
            if not opts or not isinstance(ans, list) or not all(
                isinstance(a, int) and 0 <= a < len(opts) for a in ans
            ):
                errors.append(f"{where}: multi answers out of range")
        else:
            errors.append(f"{where}: unknown type '{t}'")

quiz_pages = {s for s in pages if s.startswith(("learn/", "provinces/"))}
for s in sorted(quiz_pages - set(per_page)):
    warnings.append(f"no quiz questions for page {s}")

# --- Review markers ------------------------------------------------------
marker_re = re.compile(r"<!--\s*(check:?|unverified link:?)\s*(.*?)\s*-->|#\s*(check|unverified link):?\s*(.*)$", re.S)
markers: list[tuple[str, int, str, str]] = []
# Compiled reference pages repeat markers from the pages they were built from.
COMPILED = {"sources.en.md", "glossary.en.md", "timeline.en.md", "myths.en.md"}
for f in sorted(CONTENT.rglob("*.en.*")):
    if f.parent == CONTENT and f.name in COMPILED:
        continue
    text = f.read_text()
    for m in marker_re.finditer(text):
        kind = (m.group(1) or m.group(3)).rstrip(":")
        note = " ".join((m.group(2) or m.group(4) or "").split())
        line = text.count("\n", 0, m.start()) + 1
        markers.append((str(f.relative_to(ROOT)), line, kind, note))
checks = sum(1 for m in markers if m[2] == "check")
unverified = sum(1 for m in markers if m[2] == "unverified link")

if "--review" in sys.argv:
    out = ["# Review list", "",
           "Generated by `uv run --with pyyaml python scripts/validate.py --review`.",
           "Don't edit by hand: resolve the marker in the content file, then regenerate.", "",
           f"**{checks}** facts to double-check · **{unverified}** links to confirm in a browser", ""]
    current = None
    for path, line, kind, note in markers:
        if path != current:
            out += ["", f"## {path}", ""]
            current = path
        label = "Check" if kind == "check" else "Link"
        out.append(f"- [ ] **{label}** ([line {line}]({path}:{line})): {note or '(no note)'}")
    (ROOT / "REVIEW.md").write_text("\n".join(out).replace("\n\n\n", "\n\n") + "\n")
    print("Wrote REVIEW.md")

print(f"Pages: {len(pages)}  status: {status_counts}")
print(f"Quiz questions: {len(seen_ids)}")
print(f"Review markers: {checks} check comments, {unverified} unverified links")
for w in warnings:
    print("WARN ", w)
for e in errors:
    print("ERROR", e)
sys.exit(1 if errors else 0)
