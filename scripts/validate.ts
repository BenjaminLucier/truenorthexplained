/**
 * Content checks that the Astro build doesn't cover on its own:
 * internal links, quiz page references, pages without questions, the
 * semantic layer (entity links `[…](type:slug)`, `about:` ids, the entity YAML
 * and its page targets, links and facts in the YAML's inline markdown such as
 * event `text`, `{{fact}}` keys), the glossary term files
 * (content/glossary/*.en.md: fields, `see` pages, `alias_of`) and the review markers
 * (`<!-- check -->`, `<!-- unverified link -->`, and `# check:` in YAML).
 *
 *   pnpm validate          check everything
 *   pnpm review            also regenerate REVIEW.md
 *
 * Front matter and quiz fields are validated by the schemas in
 * src/content.config.ts during `pnpm build`.
 */
import { readFile, writeFile } from "node:fs/promises";
import { glob } from "node:fs/promises";
import { relative, resolve } from "node:path";
import { parse } from "yaml";
import { sitePathFromEntry } from "../src/lib/paths.ts";
import { ENTITY_LINK_RE, allEntities, checkEntityPages, entityNotes, getEntity } from "../src/lib/entities.ts";
import { FACT_LIKE_RE, FACT_RE, allFacts, getFact } from "../src/lib/facts.ts";
import { checkTerms, readTermFiles } from "../src/lib/glossary-terms.ts";

const ROOT = resolve(import.meta.dirname, "..");
const CONTENT = resolve(ROOT, "content");
/** Routes generated by src/pages rather than a content file. */
const GENERATED = ["", "learn", "tour", "quizzes", "design"];
/** Compiled reference pages repeat markers from the pages they were built from. */
const COMPILED = new Set(["sources.en.md", "glossary.en.md", "timeline.en.md", "myths.en.md"]);

const errors: string[] = [];
const warnings: string[] = [];
const rel = (p: string) => relative(ROOT, p);

const pageFiles: string[] = [];
// Glossary terms (content/glossary/) are not pages; they're checked below.
for await (const f of glob("**/*.en.md", { cwd: CONTENT, exclude: ["glossary/**"] })) pageFiles.push(f);
pageFiles.sort();
const pages = new Map(pageFiles.map((f) => [sitePathFromEntry(f), resolve(CONTENT, f)]));
const validPaths = new Set([...pages.keys(), ...GENERATED]);
validPaths.delete("home");

// The entity registry and facts: loading them checks the YAML (fields, types,
// duplicate ids, references between entities) and the derivations.
let entityCount: Record<string, number> = {};
let entitiesOk = false;
try {
  for (const e of allEntities()) entityCount[e.type] = (entityCount[e.type] ?? 0) + 1;
  errors.push(...checkEntityPages(validPaths));
  entitiesOk = true;
} catch (e) {
  errors.push(...(e as Error).message.split("\n").map((l) => l.trim()).filter(Boolean));
  entityCount = {};
}
let factsOk = false;
try {
  allFacts();
  factsOk = true;
} catch (e) {
  errors.push(...(e as Error).message.split("\n").map((l) => l.trim()).filter(Boolean));
}
const checkEntity = (where: string, id: string) => {
  if (!entitiesOk) return;
  try {
    getEntity(id);
  } catch (e) {
    errors.push(`${where}: ${(e as Error).message}`);
  }
};
/** Markdown without inline code and non-Mermaid fenced code, which may show `{{key}}` literally. */
const blank = (s: string) => s.replace(/[^\n]/g, " ");
const withoutCode = (text: string) =>
  text.replace(/^(```|~~~)(?!mermaid)[^\n]*\n[\s\S]*?^\1[^\n]*$/gm, blank).replace(/`[^`\n]*`/g, blank);
// Glossary term files: fields, duplicate slugs, `alias_of` targets and `see` pages.
// (The registry reports the same problems, without the page check, when it loads.)
const glossary = readTermFiles();
if (entitiesOk) errors.push(...glossary.problems, ...checkTerms(glossary.terms, validPaths));
const glossaryFiles = glossary.terms.map((t) => resolve(ROOT, t.source));
let entityLinks = 0;
let aboutIds = 0;
const factsUsed = new Map<string, number>();

// Internal links, entity links, `about:` and facts
const linkRe = /\]\((\/[^)\s#]*)(?:#[^)]*)?\)/g;
const statuses: Record<string, number> = {};
// Pages, then glossary term files (their definitions can hold links, entity links and facts).
for (const file of [...pages.values(), ...glossaryFiles]) {
  const text = await readFile(file, "utf8");
  if (!glossaryFiles.includes(file)) {
    const status = text.match(/^status:\s*(\w+)/m)?.[1] ?? "missing";
    statuses[status] = (statuses[status] ?? 0) + 1;
  }
  for (const m of text.matchAll(linkRe)) {
    const target = m[1]!.replace(/^\/|\/$/g, "");
    if (!validPaths.has(target)) errors.push(`${rel(file)}: broken internal link /${target}`);
  }
  for (const m of text.matchAll(ENTITY_LINK_RE)) {
    entityLinks++;
    checkEntity(`${rel(file)}:${text.slice(0, m.index).split("\n").length}`, m[1]!);
  }
  const front = text.match(/^---\n([\s\S]*?)\n---/)?.[1];
  const about = front ? (parse(front) as { about?: unknown }).about : undefined;
  if (about !== undefined) {
    if (!Array.isArray(about)) errors.push(`${rel(file)}: about: must be a list of entity ids`);
    else for (const id of about) (aboutIds++, checkEntity(`${rel(file)}: about`, String(id)));
  }
  const body = withoutCode(text);
  for (const m of body.matchAll(FACT_LIKE_RE)) {
    const where = `${rel(file)}:${body.slice(0, m.index).split("\n").length}`;
    const valid = [...m[0].matchAll(FACT_RE)][0];
    if (!valid || valid[0] !== m[0]) {
      errors.push(`${where}: malformed fact placeholder ${m[0]} (write {{key}} or {{key|raw}}, key in lowercase)`);
      continue;
    }
    factsUsed.set(valid[1]!, (factsUsed.get(valid[1]!) ?? 0) + 1);
    if (!factsOk) continue;
    try {
      getFact(valid[1]!);
    } catch (e) {
      errors.push(`${where}: ${(e as Error).message}`);
    }
  }
}

// Inline markdown in the entity YAML (an event's `text`, a case's `holding`, any
// `summary`) is rendered on the timelines: check its links and facts like a page's.
for (const e of entitiesOk ? allEntities() : []) {
  const fields = { summary: e.summary, ...(e.type === "event" ? { text: e.text } : e.type === "case" ? { holding: e.holding } : {}) };
  for (const [field, md] of Object.entries(fields)) {
    if (!md) continue;
    const where = `${e.source}: ${e.id}: ${field}`;
    for (const m of md.matchAll(linkRe)) {
      const target = m[1]!.replace(/^\/|\/$/g, "");
      if (!validPaths.has(target)) errors.push(`${where}: broken internal link /${target}`);
    }
    for (const m of md.matchAll(ENTITY_LINK_RE)) (entityLinks++, checkEntity(where, m[1]!));
    for (const m of md.matchAll(FACT_LIKE_RE)) {
      const valid = [...m[0].matchAll(FACT_RE)][0];
      if (!valid || valid[0] !== m[0]) errors.push(`${where}: malformed fact placeholder ${m[0]}`);
      else if (factsOk) {
        try {
          getFact(valid[1]!);
        } catch (err) {
          errors.push(`${where}: ${(err as Error).message}`);
        }
      }
    }
  }
}

// Quizzes
interface RawQuestion {
  id?: string;
  pages?: string[];
}
const seen = new Map<string, string>();
const perPage = new Map<string, number>();
const quizFiles: string[] = [];
for await (const f of glob("quizzes/*.en.yaml", { cwd: CONTENT })) quizFiles.push(resolve(CONTENT, f));
for (const file of quizFiles.sort()) {
  let questions: RawQuestion[];
  try {
    questions = (parse(await readFile(file, "utf8")) as RawQuestion[] | null) ?? [];
  } catch (e) {
    errors.push(`${rel(file)}: YAML error: ${(e as Error).message}`);
    continue;
  }
  for (const q of questions) {
    const id = q.id ?? "<no id>";
    if (seen.has(id)) errors.push(`${rel(file)}: ${id}: duplicate id (also in ${seen.get(id)})`);
    seen.set(id, rel(file));
    for (const p of q.pages ?? []) {
      if (!pages.has(p)) errors.push(`${rel(file)}: ${id}: unknown page "${p}"`);
      perPage.set(p, (perPage.get(p) ?? 0) + 1);
    }
  }
}
for (const id of pages.keys()) {
  if (/^(learn|provinces)\//.test(id) && !perPage.has(id)) warnings.push(`no quiz questions for page ${id}`);
}

// Review markers
const markerRe = /<!--\s*(check|unverified link):?\s*([\s\S]*?)\s*-->|#\s*(check|unverified link):?\s*(.*)$/gm;
interface Marker {
  file: string;
  line: number;
  kind: string;
  note: string;
}
const markers: Marker[] = [];
const markerFiles: string[] = [];
for await (const f of glob("**/*.en.{md,yaml}", { cwd: CONTENT })) markerFiles.push(f);
// Entity and fact YAML carry `# check:` comments too.
for await (const f of glob(["entities/*.yaml", "facts.yaml"], { cwd: CONTENT })) markerFiles.push(f);
for (const f of markerFiles.sort()) {
  if (COMPILED.has(f)) continue;
  const file = resolve(CONTENT, f);
  const text = await readFile(file, "utf8");
  for (const m of text.matchAll(markerRe)) {
    markers.push({
      file: rel(file),
      line: text.slice(0, m.index).split("\n").length,
      kind: m[1] ?? m[3] ?? "check",
      note: (m[2] ?? m[4] ?? "").replace(/\s+/g, " ").trim(),
    });
  }
}
const checks = markers.filter((m) => m.kind === "check").length;
const unverified = markers.length - checks;

if (process.argv.includes("--review")) {
  const out = [
    "# Review list",
    "",
    "Generated by `pnpm review`. Don't edit by hand: resolve the marker in the content file, then regenerate.",
    "",
    `**${checks}** facts to double-check · **${unverified}** links to confirm in a browser`,
  ];
  let current = "";
  for (const m of markers) {
    if (m.file !== current) out.push("", `## ${m.file}`, "");
    current = m.file;
    const label = m.kind === "check" ? "Check" : "Link";
    out.push(`- [ ] **${label}** ([line ${m.line}](${m.file}:${m.line})): ${m.note || "(no note)"}`);
  }
  await writeFile(resolve(ROOT, "REVIEW.md"), `${out.join("\n")}\n`);
  console.log("Wrote REVIEW.md");
}

console.log(`Pages: ${pages.size}  status: ${JSON.stringify(statuses)}`);
console.log(`Glossary terms: ${glossary.terms.length} (${glossary.terms.filter((t) => t.aliasOf).length} aliases)`);
console.log(`Quiz questions: ${seen.size}`);
console.log(`Review markers: ${checks} check comments, ${unverified} unverified links`);
const typeCounts = Object.entries(entityCount).map(([t, n]) => `${t} ${n}`).join(", ");
const entityTotal = Object.values(entityCount).reduce((a, b) => a + b, 0);
console.log(`Entities: ${entityTotal} (${typeCounts})  entity links: ${entityLinks}  about ids: ${aboutIds}`);
const placeholders = [...factsUsed.values()].reduce((a, b) => a + b, 0);
console.log(`Facts: ${factsOk ? allFacts().size : 0} defined, ${factsUsed.size} used in ${placeholders} placeholders`);
for (const n of entitiesOk ? entityNotes() : []) console.log(`NOTE  ${n}`);
for (const w of warnings) console.log(`WARN  ${w}`);
for (const e of errors) console.log(`ERROR ${e}`);
process.exit(errors.length ? 1 : 0);
